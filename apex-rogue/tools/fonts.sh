#!/bin/sh
# Builds fonts.css: the bundled fonts (fonts/*.woff2, all SIL OFL 1.1: see fonts/OFL-*.txt) embedded as data URIs.
# Browsers refuse to load font files from file:// pages, and the game runs from disk, so they go inline.
set -e
cd "$(dirname "$0")/.."
face() { printf "@font-face { font-family: '%s'; font-weight: %s; font-style: normal; font-display: swap; src: url(data:font/woff2;base64,%s) format('woff2'); }\n" "$1" "$2" "$(base64 -w0 "fonts/$3")"; }
{
  echo "/* Generated by tools/fonts.sh from fonts/*.woff2 (SIL Open Font License 1.1). Don't edit by hand. */"
  face 'Anton' 400 anton-latin.woff2
  face 'Courier Prime' 400 courierprime-400-latin.woff2
  face 'Courier Prime' 700 courierprime-700-latin.woff2
  face 'Black Ops One' 400 blackopsone-latin.woff2
} > fonts.css
echo "fonts.css ($(du -h fonts.css | cut -f1))"
