#!/usr/bin/env python3
"""Builds the spoken lines: js/voices/<id>.js, one file per voice, each a VoiceBank.add({...}) of every line in
tools/voice_lines.json as a small MP3 (base64, since a page opened from disk can't fetch files).

The speech is synthesised offline with Piper (pip install piper-tts) from the LibriTTS multi-speaker model
(CC BY 4.0: https://github.com/rhasspy/piper/releases/download/v0.0.2/voice-en-us-libritts-high.tar.gz), then
roughed up with ffmpeg: a green driver's voice is pitched up, hurried and shaking, a hardened one's lower and
steady, and the shouted lines are pushed into the upper mids so they sound strained.

  python3 tools/make_voices.py path/to/en-us-libritts-high.onnx [d1,d2,...]
"""
import base64, io, json, os, subprocess, sys, wave
import numpy as np
from piper import PiperVoice
from piper.config import SynthesisConfig

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
LINES = json.load(open(os.path.join(ROOT, 'tools', 'voice_lines.json')))
OUT = os.path.join(ROOT, 'js', 'voices')

# The voices: LibriTTS speaker ids, picked for low (male) pitch and clear speech. Six drivers (each inmate who
# drives for you gets one, by their seed) and you.
DRIVERS = {'d1': 800, 'd2': 592, 'd3': 736, 'd4': 8, 'd5': 584, 'd6': 848}
GUNNER = {'gunner': 760}

# How each tier speaks: Piper's pace and wobble, then the pitch shift (ratio) and the pace again after it.
TIER = {
    'g': dict(ls=0.82, ns=0.95, nw=0.95, pitch=1.12, tempo=1.08, shake=True),
    'm': dict(ls=0.92, ns=0.75, nw=0.8, pitch=1.04, tempo=1.0, shake=False),
    'h': dict(ls=1.0, ns=0.6, nw=0.7, pitch=0.95, tempo=1.0, shake=False),
}
SHOUTED = {'jump', 'crash', 'rocket', 'mine', 'lock', 'blast', 'hit', 'shot', 'kill'}


def synth(V, text, sid, ls, ns, nw):
    buf = io.BytesIO()
    with wave.open(buf, 'wb') as w:
        V.synthesize_wav(text, w, syn_config=SynthesisConfig(speaker_id=sid, length_scale=ls, noise_scale=ns, noise_w_scale=nw))
    return buf.getvalue()


def ff(args, data):
    for attempt in range(3):  # (ffmpeg has been known to fall over now and then under memory pressure: try again)
        p = subprocess.run(['ffmpeg', '-loglevel', 'error'] + args, input=data, capture_output=True)
        if p.returncode == 0 and p.stdout: return p.stdout
    raise RuntimeError('ffmpeg failed: ' + p.stderr.decode(errors='replace')[-400:])


def rough(wav, sr, pitch, tempo, shake, shout, chest):
    f = [f'asetrate={int(sr * pitch)}', f'aresample={sr}', f'atempo={tempo / pitch:.4f}', 'highpass=f=90', 'lowpass=f=7500']
    if shake: f.append('vibrato=f=6.5:d=0.12')
    if shout: f += ['equalizer=f=2400:t=q:w=1.2:g=6', 'equalizer=f=900:t=q:w=1:g=2']
    if chest: f.append('equalizer=f=180:t=q:w=1:g=3')
    f.append('acompressor=threshold=-22dB:ratio=5:attack=4:release=60:makeup=2')
    raw = ff(['-f', 'wav', '-i', '-', '-af', ','.join(f), '-ar', '22050', '-ac', '1', '-f', 's16le', '-'], wav)
    x = np.frombuffer(raw, dtype='<i2').astype(np.float64)
    x = np.nan_to_num(x)
    # Trim the silence off both ends (only the ends: pauses between words stay), with a few ms of air either side.
    env = np.convolve(np.abs(x), np.ones(110) / 110, 'same')
    loud = np.nonzero(env > max(200.0, env.max() * 0.03))[0]
    if len(loud): x = x[max(0, loud[0] - 220):min(len(x), loud[-1] + 660)]
    # The same loudness for every line (by RMS), never clipping.
    rms = np.sqrt(np.mean(x ** 2)) or 1.0
    x = x * min(5500.0 / rms, 31000.0 / (np.abs(x).max() or 1.0))
    pcm = np.clip(x, -32767, 32767).astype('<i2').tobytes()
    mp3 = ff(['-f', 's16le', '-ar', '22050', '-ac', '1', '-i', '-', '-c:a', 'libmp3lame', '-b:a', '32k', '-f', 'mp3', '-'], pcm)
    return base64.b64encode(mp3).decode()


def bank(V, sr, vid, sid, who):
    lines = {}
    if who == 'driver':
        for cat, tiers in LINES['driver'].items():
            lines[cat] = {}
            for t, items in tiers.items():
                T = TIER[t]
                out = []
                for it in items:
                    text, say = (it, it) if isinstance(it, str) else (it[0], it[1])
                    wav = synth(V, say, sid, T['ls'], T['ns'], T['nw'])
                    out.append([text, rough(wav, sr, T['pitch'], T['tempo'], T['shake'], cat in SHOUTED and t != 'h', t == 'h')])
                lines[cat][t] = out
    else:
        for cat, items in LINES['gunner'].items():
            out = []
            for it in items:
                wav = synth(V, it, sid, 0.75, 0.8, 0.8)
                out.append([it, rough(wav, sr, 0.97, 1.0, False, cat != 'impact', True)])
            lines[cat] = out
    js = f"VoiceBank.add({json.dumps({'id': vid, 'who': who, 'lines': lines}, separators=(',', ':'))});\n"
    path = os.path.join(OUT, vid + '.js')
    open(path, 'w').write("'use strict';\n// Generated by tools/make_voices.py from tools/voice_lines.json (LibriTTS voice, CC BY 4.0). Don't edit by hand.\n" + js)
    return path, len(js)


def main():
    model = sys.argv[1] if len(sys.argv) > 1 else 'en-us-libritts-high.onnx'
    V = PiperVoice.load(model)
    sr = V.config.sample_rate
    os.makedirs(OUT, exist_ok=True)
    only = sys.argv[2].split(',') if len(sys.argv) > 2 else None  # (just these voices)
    for vid, sid in list(DRIVERS.items()) + list(GUNNER.items()):
        if only and vid not in only: continue
        path, n = bank(V, sr, vid, sid, 'gunner' if vid == 'gunner' else 'driver')
        print(f'{os.path.relpath(path, ROOT)}: {n // 1024} KB')


if __name__ == '__main__':
    main()
